export const MaterialesBrutosTab: React.FC = () => {
    const { addNotification } = useAppContext();
    const [allData, setAllData] = useState<MaterialBrutoItem[]>([]); 
    const [isLoading, setIsLoading] = useState(false);
    const [isScanning, setIsScanning] = useState(false);
    const [columns, setColumns] = useState<string[]>([]);
    const [searchTerm, setSearchTerm] = useState('');
    const [currentPage, setCurrentPage] = useState(1);
    const [rowsPerPage, setRowsPerPage] = useState(ROWS_PER_PAGE_OPTIONS[3]); // Default a 200
    const [totalRecords, setTotalRecords] = useState(0);
    const [scannedRecordsCount, setScannedRecordsCount] = useState(0);
    const [loadedBlocks, setLoadedBlocks] = useState<Set<number>>(new Set());

    // Refs para scrollbar doble
    const topScrollRef = useRef<HTMLDivElement>(null);
    const tableScrollRef = useRef<HTMLDivElement>(null);
    const tableRef = useRef<HTMLTableElement>(null);
    const [tableWidth, setTableWidth] = useState(0);
    const lastScrolledRef = useRef<'top' | 'table' | null>(null);

    // Filtrado dinámico MEMOIZADO para CASCO y TELA
    const filteredData = useMemo(() => {
        return allData.filter(row => {
            const fertCodeRaw = String(row.FERT_PRINCIPAL || '');
            const fertCodeNormalized = fertCodeRaw.replace(/^0+/, ''); 
            
            // Filtro 1: Debe estar en la lista permitida de muebles
            if (!ALLOWED_FERT_CODES.has(fertCodeNormalized)) return false;

            // Filtro 2: Solo CASCO y TELA (según requerimiento de descripción padre y componente)
            const rowString = Object.values(row).join(' ').toUpperCase();
            const hasKeyword = ['CASCO', 'TELA'].some(key => rowString.includes(key));
            
            if (!hasKeyword) return false;

            // Filtro 3: Search term manual
            if (searchTerm.trim()) {
                const term = searchTerm.toLowerCase();
                return Object.values(row).some(val => String(val).toLowerCase().includes(term));
            }

            return true;
        });
    }, [allData, searchTerm]);

    const loadBlock = async (blockPage: number): Promise<MaterialBrutoItem[]> => {
        if (loadedBlocks.has(blockPage)) return [];

        try {
            const response = await serviciosService.getMaterialesBrutosPorMaterialMateriaPrima(blockPage, BLOCK_SIZE);
            if (response && response.data) {
                const dataArray = Array.isArray(response.data) ? response.data : [response.data];
                
                if (blockPage === 1) {
                    setTotalRecords(response.totalRegistros || response.totalRecords || 0);
                    if (dataArray.length > 0) {
                        setColumns(Object.keys(dataArray[0]));
                    }
                }

                setAllData(prev => [...prev, ...dataArray]);
                setLoadedBlocks(prev => new Set([...prev, blockPage]));
                setScannedRecordsCount(prev => prev + dataArray.length);
                return dataArray;
            }
            return [];
        } catch (error) {
            console.error('Error al cargar bloque:', error);
            return [];
        }
    };

    // Efecto de carga inicial y escaneo profundo automático para CASCOS y TELAS
    useEffect(() => {
        const initialScan = async () => {
            setIsLoading(true);
            setIsScanning(true);
            
            let currentBlock = 1;
            let foundCount = 0;
            // Escaneo profundo (hasta 100k registros)
            const MAX_BLOCKS_TO_SCAN = 20; 

            while (foundCount < 10 && currentBlock <= MAX_BLOCKS_TO_SCAN) {
                const newRows = await loadBlock(currentBlock);
                if (newRows.length === 0) break;

                const matchesInBlock = newRows.filter(row => {
                    const fertCodeRaw = String(row.FERT_PRINCIPAL || '').replace(/^0+/, '');
                    const isMueble = ALLOWED_FERT_CODES.has(fertCodeRaw);
                    const rowString = Object.values(row).join(' ').toUpperCase();
                    const hasKeyword = ['CASCO', 'TELA'].some(key => rowString.includes(key));
                    return isMueble && hasKeyword;
                }).length;

                foundCount += matchesInBlock;
                currentBlock++;

                if (foundCount >= 10) break;
            }

            setIsLoading(false);
            setIsScanning(false);
        };

        initialScan();
    }, []);

    const totalPages = Math.max(1, Math.ceil(filteredData.length / rowsPerPage));

    const displayedData = useMemo(() => {
        const start = (currentPage - 1) * rowsPerPage;
        return filteredData.slice(start, start + rowsPerPage);
    }, [filteredData, currentPage, rowsPerPage]);

    const handlePageChange = (page: number) => {
        const newPage = Math.max(1, Math.min(page, totalPages));
        setCurrentPage(newPage);

        const threshold = displayedData.length + rowsPerPage;
        if (filteredData.length < threshold && scannedRecordsCount < totalRecords) {
            const nextBlock = Math.ceil(allData.length / BLOCK_SIZE) + 1;
            loadBlock(nextBlock);
        }
    };

    // Sincronización de scrollbars
    useEffect(() => {
        const calculateWidth = () => {
            if (tableRef.current) setTableWidth(tableRef.current.offsetWidth);
        };
        calculateWidth();
        window.addEventListener('resize', calculateWidth);
        const resizeObserver = new ResizeObserver(calculateWidth);
        if (tableRef.current) resizeObserver.observe(tableRef.current);
        return () => {
            window.removeEventListener('resize', calculateWidth);
            if (tableRef.current) resizeObserver.unobserve(tableRef.current);
        };
    }, [displayedData]);

    const handleTopScroll = (e: React.UIEvent<HTMLDivElement>) => {
        if (lastScrolledRef.current === 'table') { lastScrolledRef.current = null; return; }
        if (tableScrollRef.current) {
            lastScrolledRef.current = 'top';
            tableScrollRef.current.scrollLeft = e.currentTarget.scrollLeft;
        }
    };

    const handleTableScroll = (e: React.UIEvent<HTMLDivElement>) => {
        if (lastScrolledRef.current === 'top') { lastScrolledRef.current = null; return; }
        if (topScrollRef.current) {
            lastScrolledRef.current = 'table';
            topScrollRef.current.scrollLeft = e.currentTarget.scrollLeft;
        }
    };

    return (
        <div className="space-y-4">
            <div className="flex flex-col md:flex-row gap-4 items-center justify-between">
                <div className="relative w-full md:w-96">
                    <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-gray-400" />
                    <Input 
                        placeholder="Buscar en resultados..." 
                        className="pl-10"
                        value={searchTerm}
                        onChange={(e) => { setSearchTerm(e.target.value); setCurrentPage(1); }}
                    />
                </div>
                {(isLoading || isScanning) && (
                    <div className="flex items-center gap-3 text-sm text-blue-600 font-medium animate-pulse">
                        <Loader2 className="h-4 w-4 animate-spin" />
                        {isScanning ? `Buscando Cascos y Telas... (${scannedRecordsCount.toLocaleString()} revisados)` : 'Cargando...'}
                    </div>
                )}
            </div>

            <div className="bg-indigo-50 border border-indigo-200 p-4 rounded-lg flex items-start gap-3">
                <Filter className="w-5 h-5 text-indigo-600 mt-0.5 flex-shrink-0" />
                <div className="text-xs text-indigo-800">
                    <p className="font-bold mb-1 uppercase">Explosión de Insumos: Cascos y Telas</p>
                    <p>Esta vista muestra exclusivamente los insumos de tipo <strong>CASCO</strong> y <strong>TELA</strong> para los productos FERT seleccionados.</p>
                    <p className="mt-1">Los códigos se muestran simplificados (sin los primeros 8 ceros) para mayor claridad.</p>
                </div>
            </div>

            {filteredData.length > 0 ? (
                <>
                    <div ref={topScrollRef} onScroll={handleTopScroll} className="overflow-x-auto overflow-y-hidden h-[18px]">
                        <div style={{ width: `${tableWidth}px`, height: '1px' }}></div>
                    </div>

                    <div ref={tableScrollRef} onScroll={handleTableScroll} className="border rounded-lg overflow-auto max-h-[60vh]">
                        <table ref={tableRef} className="min-w-full text-xs border-collapse">
                            <thead className="bg-gray-100 sticky top-0 z-10 shadow-sm">
                                <tr className="border-b-2 border-gray-300">
                                    {columns.map(col => (
                                        <TableHead key={col} className="text-center font-bold text-gray-700 uppercase tracking-wider px-4 py-3 border-r border-dashed border-gray-300 last:border-r-0 whitespace-nowrap">
                                            {col}
                                        </TableHead>
                                    ))}
                                </tr>
                            </thead>
                            <tbody className="divide-y divide-gray-100">
                                {displayedData.map((row, idx) => (
                                    <tr key={idx} className="hover:bg-blue-50/30 transition-colors">
                                        {columns.map((col, cIdx) => {
                                            let val = String(row[col] ?? '-');
                                            
                                            if (['FERT_PRINCIPAL', 'MATERIAL_PADRE', 'COMPONENTE'].includes(col)) {
                                                val = val.replace(/^0{8}/, '');
                                            }

                                            return (
                                                <TableCell key={`${idx}-${cIdx}`} className="px-4 py-2.5 text-center border-r border-dashed border-gray-200 last:border-r-0 whitespace-nowrap">
                                                    {val}
                                                </TableCell>
                                            );
                                        })}
                                    </tr>
                                ))}
                            </tbody>
                        </table>
                    </div>

                    <div className="flex items-center justify-between mt-4">
                        <div className="flex items-center space-x-2">
                            <span className="text-sm text-gray-600">Filas por página:</span>
                            <select
                                value={rowsPerPage}
                                onChange={(e) => { setRowsPerPage(Number(e.target.value)); handlePageChange(1); }}
                                className="px-3 py-2 border rounded-md text-sm bg-white"
                            >
                                {ROWS_PER_PAGE_OPTIONS.map(size => <option key={size} value={size}>{size}</option>)}
                            </select>
                        </div>
                        <div className="flex items-center space-x-2">
                            <span className="text-sm text-gray-600 font-medium">
                                Página {currentPage} de {totalPages} ({filteredData.length.toLocaleString()} insumos encontrados)
                            </span>
                            <div className="flex gap-1 ml-4">
                                <Button variant="outline" size="sm" onClick={() => handlePageChange(1)} disabled={currentPage === 1}>Primera</Button>
                                <Button variant="outline" size="sm" onClick={() => handlePageChange(currentPage - 1)} disabled={currentPage === 1}>Anterior</Button>
                                <Button variant="outline" size="sm" onClick={() => handlePageChange(currentPage + 1)} disabled={currentPage >= totalPages}>Siguiente</Button>
                                <Button variant="outline" size="sm" onClick={() => handlePageChange(totalPages)} disabled={currentPage >= totalPages}>Última</Button>
                            </div>
                        </div>
                    </div>
                </>
            ) : (
                <div className="flex flex-col items-center justify-center py-20 bg-gray-50 border-2 border-dashed rounded-xl text-center px-4">
                    {isScanning ? (
                        <>
                            <Loader2 className="w-10 h-10 animate-spin text-blue-500 mb-4" />
                            <p className="text-blue-800 font-semibold text-lg">Buscando Cascos y Telas...</p>
                            <p className="text-blue-600 mt-2">Revisando profundamente la base de datos para localizar tus insumos.</p>
                        </>
                    ) : (
                        <>
                            <Database className="w-12 h-12 text-gray-300 mb-4" />
                            <p className="text-gray-500 text-lg font-medium">No se encontraron Cascos ni Telas</p>
                            <p className="text-gray-400 text-sm mt-1 max-w-md">
                                El sistema ha revisado los registros y no ha encontrado insumos que contengan "CASCO" o "TELA" para los productos FERT de muebles seleccionados.
                            </p>
                        </>
                    )}
                </div>
            )}
        </div>
    );
};
